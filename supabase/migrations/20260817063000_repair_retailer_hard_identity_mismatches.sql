-- Retire a bad serving row only when no unaffected promoted evidence supports
-- it. A legitimate sibling (for example an adult size next to a puppy size)
-- remains live while only the incorrect package relationship is detached.
WITH exclusive_bad_cache AS (
  SELECT DISTINCT repair.old_cache_key
  FROM public.catalog_retailer_identity_repairs repair
  WHERE repair.new_formula_id IS NULL
    AND repair.old_cache_key IS NOT NULL
    AND NOT EXISTS (
      SELECT 1
      FROM public.catalog_retailer_ingredient_evidence evidence
      WHERE evidence.is_current
        AND evidence.evidence_status = 'promoted'
        AND evidence.promoted_cache_key = repair.old_cache_key
        AND NOT EXISTS (
          SELECT 1
          FROM public.catalog_retailer_identity_repairs same_repair
          WHERE same_repair.evidence_id = evidence.id
            AND same_repair.new_formula_id IS NULL
        )
    )
), cleared_formula_pointer AS (
  UPDATE public.catalog_formulas formula
  SET promoted_cache_key = NULL, updated_at = now()
  FROM exclusive_bad_cache bad
  WHERE formula.promoted_cache_key = bad.old_cache_key
  RETURNING formula.id
)
UPDATE public.product_data serving
SET
  expires_at = LEAST(COALESCE(serving.expires_at, now()), now()),
  catalog_exclusion_reason = 'retailer_hard_identity_mismatch_repaired',
  updated_at = now()
FROM exclusive_bad_cache bad
WHERE serving.cache_key = bad.old_cache_key;


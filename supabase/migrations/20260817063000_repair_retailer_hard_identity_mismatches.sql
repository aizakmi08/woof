  evidence_status = 'promotable_exact_package',
  updated_at = now()
FROM public.catalog_retailer_identity_repairs repair,
  public.catalog_observations observation
WHERE evidence.id = repair.evidence_id
  AND observation.formula_id = evidence.linked_formula_id
  AND observation.source_slug = evidence.source_slug || '-retailer-web'
  AND observation.source_external_id = evidence.source_external_id
  AND observation.content_hash =
    evidence.content_hash || ':' || evidence.image_content_hash || ':hard-identity-v1'
  AND repair.new_formula_id IS NULL;


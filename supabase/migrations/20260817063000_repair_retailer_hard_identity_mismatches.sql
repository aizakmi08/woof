-- Prevent a future materialization from reusing an existing formula by GTIN
-- or exact title when any structured hard boundary conflicts.
DO $migration$
DECLARE
  v_definition TEXT;
  v_fixed_definition TEXT;
  v_gtin_marker TEXT := $old$     AND formula.pet_type = evidence.pet_type
    WHERE evidence.id = ANY(v_ids)$old$;
  v_gtin_replacement TEXT := $new$     AND formula.pet_type = evidence.pet_type
     AND public.catalog_retailer_formula_hard_boundaries_match(
       evidence.retailer_brand,
       evidence.pet_type,
       evidence.life_stage,
       evidence.food_form,
       evidence.flavor,
       evidence.diet_condition,
       formula.brand,
       formula.pet_type,
       formula.life_stage,
       formula.food_form,
       formula.flavor,
       formula.diet_condition
     )
    WHERE evidence.id = ANY(v_ids)$new$;
  v_title_marker TEXT := $old$     AND formula.pet_type = evidence.pet_type
     AND (
       public.catalog_normalize_retailer_title(formula.product_name)$old$;
  v_title_replacement TEXT := $new$     AND formula.pet_type = evidence.pet_type
     AND public.catalog_retailer_formula_hard_boundaries_match(
       evidence.retailer_brand,
       evidence.pet_type,
       evidence.life_stage,
       evidence.food_form,
       evidence.flavor,
       evidence.diet_condition,
       formula.brand,
       formula.pet_type,
       formula.life_stage,
       formula.food_form,
       formula.flavor,
       formula.diet_condition
     )
     AND (
       public.catalog_normalize_retailer_title(formula.product_name)$new$;
BEGIN
  SELECT pg_get_functiondef(
    'public.materialize_retailer_web_formulas(uuid,integer)'::regprocedure
  ) INTO v_definition;

  v_fixed_definition := replace(v_definition, v_gtin_marker, v_gtin_replacement);
  v_fixed_definition := replace(v_fixed_definition, v_title_marker, v_title_replacement);

  IF v_fixed_definition = v_definition
    OR position('catalog_retailer_formula_hard_boundaries_match' IN v_fixed_definition) = 0
  THEN
    RAISE EXCEPTION 'retailer materializer hard-boundary markers not found';
  END IF;
  EXECUTE v_fixed_definition;
END;
$migration$;

CREATE OR REPLACE FUNCTION public.guard_retailer_formula_hard_boundaries()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $function$
DECLARE
  v_formula public.catalog_formulas%ROWTYPE;
BEGIN
  IF NEW.linked_formula_id IS NULL
    OR NEW.evidence_status NOT IN ('promotable_exact_package', 'promoted')
  THEN
    RETURN NEW;
  END IF;

  SELECT * INTO v_formula
  FROM public.catalog_formulas
  WHERE id = NEW.linked_formula_id;

  IF v_formula.id IS NOT NULL
    AND NOT public.catalog_retailer_formula_hard_boundaries_match(
      NEW.retailer_brand,
      NEW.pet_type,
      NEW.life_stage,
      NEW.food_form,
      NEW.flavor,
      NEW.diet_condition,
      v_formula.brand,
      v_formula.pet_type,
      v_formula.life_stage,
      v_formula.food_form,
      v_formula.flavor,
      v_formula.diet_condition
    )
  THEN
    NEW.evidence_status := 'quarantined_validation';
    NEW.promoted_cache_key := NULL;
    IF NOT ('retailer_hard_identity_mismatch' = ANY(NEW.validation_reasons)) THEN
      NEW.validation_reasons := array_append(
        NEW.validation_reasons,
        'retailer_hard_identity_mismatch'
      );
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS guard_retailer_formula_hard_boundaries
  ON public.catalog_retailer_ingredient_evidence;
CREATE TRIGGER guard_retailer_formula_hard_boundaries
BEFORE INSERT OR UPDATE OF linked_formula_id, evidence_status
ON public.catalog_retailer_ingredient_evidence
FOR EACH ROW EXECUTE FUNCTION public.guard_retailer_formula_hard_boundaries();

-- Snapshot every affected relationship before changing derived state.
WITH affected AS (
  SELECT
    evidence.id AS evidence_id,
    evidence.import_run_id,
    evidence.source_slug,
    evidence.source_external_id,
    evidence.source_url,
    evidence.linked_formula_id,
    evidence.linked_observation_id,
    evidence.promoted_cache_key,
    serving.product_name AS old_product_name,
    serving.life_stage AS old_life_stage,
    serving.food_form AS old_food_form,
    evidence.formula_title AS evidence_product_name,
    evidence.life_stage AS evidence_life_stage,
    evidence.food_form AS evidence_food_form,
    ARRAY_REMOVE(ARRAY[
      CASE WHEN
        public.catalog_normalize_retailer_boundary(evidence.food_form)
          NOT IN ('', 'unknown', 'other')
        AND public.catalog_normalize_retailer_boundary(serving.food_form)
          NOT IN ('', 'unknown', 'other')
        AND public.catalog_normalize_retailer_boundary(evidence.food_form)
          <> public.catalog_normalize_retailer_boundary(serving.food_form)
        THEN 'food_form_mismatch' END,
      CASE WHEN
        public.catalog_normalize_retailer_boundary(evidence.life_stage)
          NOT IN ('', 'unknown', 'other')
        AND public.catalog_normalize_retailer_boundary(serving.life_stage)
          NOT IN ('', 'unknown', 'other')
        AND NOT (
          public.catalog_normalize_retailer_boundary(evidence.life_stage)
            = public.catalog_normalize_retailer_boundary(serving.life_stage)
          OR (
            public.catalog_normalize_retailer_boundary(evidence.life_stage) = 'adult'
            AND public.catalog_normalize_retailer_boundary(serving.life_stage)
              IN ('adultmature', 'adultmaturesenior')
          )
          OR (
            public.catalog_normalize_retailer_boundary(evidence.life_stage) = 'senior'
            AND public.catalog_normalize_retailer_boundary(serving.life_stage)
              IN ('adultmature', 'adultmaturesenior')
          )
        )
        THEN 'life_stage_mismatch' END
    ], NULL) AS mismatch_reasons
  FROM public.catalog_retailer_ingredient_evidence evidence
  JOIN public.product_data serving
    ON serving.cache_key = evidence.promoted_cache_key
  WHERE evidence.is_current
    AND evidence.evidence_status = 'promoted'
    AND evidence.image_validation_status = 'exact_retailer_sku'
    AND evidence.formula_identity_hash ~ '^[0-9a-f]{64}$'
    AND public.catalog_retailer_ingredient_is_serving_safe(
      COALESCE(NULLIF(evidence.serving_ingredient_text, ''), evidence.ingredient_text)
    )
), inserted AS (
  INSERT INTO public.catalog_retailer_identity_repairs (
    evidence_id, import_run_id, source_slug, source_external_id, source_url,
    old_formula_id, old_observation_id, old_cache_key, old_product_name,
    old_life_stage, old_food_form, evidence_product_name,
    evidence_life_stage, evidence_food_form, mismatch_reasons
  )
  SELECT
    evidence_id, import_run_id, source_slug, source_external_id, source_url,
    linked_formula_id, linked_observation_id, promoted_cache_key,
    old_product_name, old_life_stage, old_food_form, evidence_product_name,
    evidence_life_stage, evidence_food_form, mismatch_reasons
  FROM affected
  WHERE cardinality(mismatch_reasons) > 0
  ON CONFLICT (evidence_id) DO NOTHING
  RETURNING evidence_id
)
SELECT count(*) FROM inserted;

